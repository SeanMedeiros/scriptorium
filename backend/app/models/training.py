"""Model training (Phase 6, master prompt §14).

A training job fine-tunes (or trains from scratch) a Kraken recognition model on the
ground-truth pages of one evaluation dataset:

* `train` split  → training data;
* `validation` split → checkpoint selection (early stopping / best model);
* `test` split → never seen during training; optionally evaluated afterwards with the
  ordinary evaluation machinery (Phase 5).

The exact data used (ground-truth snapshot ids, line counts, SHA-256 of every generated PAGE
file), the configuration, the seed and the software versions are frozen in `data_manifest` and
`config` when the job starts. Training runs in a separate process on the dedicated `training`
queue, never on the recognition workers.
"""
from __future__ import annotations

import enum
import uuid
from datetime import datetime

from sqlalchemy import BigInteger, Boolean, DateTime, Float, ForeignKey, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base, UUIDPk, utcnow
from app.models.core import _enum


class TrainingStatus(str, enum.Enum):
    QUEUED = "queued"
    PREPARING = "preparing"
    TRAINING = "training"
    REGISTERING = "registering"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class TrainingJob(UUIDPk, Base):
    __tablename__ = "training_jobs"

    project_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("projects.id", ondelete="CASCADE"), index=True)
    dataset_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("evaluation_datasets.id", ondelete="RESTRICT"), index=True)
    base_model_version_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("model_versions.id", ondelete="RESTRICT"))
    output_name: Mapped[str] = mapped_column(String(200))  # name of the institutional model to create / extend
    config: Mapped[dict] = mapped_column(JSONB)
    status: Mapped[TrainingStatus] = mapped_column(_enum(TrainingStatus, "training_status"), index=True)
    progress: Mapped[float] = mapped_column(Float, default=0.0, server_default="0")
    stage: Mapped[str | None] = mapped_column(String(60))
    current_epoch: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    epochs: Mapped[list] = mapped_column(JSONB, default=list, server_default="[]")  # [{epoch, val_accuracy, ...}]
    checkpoints: Mapped[list] = mapped_column(JSONB, default=list, server_default="[]")  # [{name, epoch, val_accuracy, bytes, deleted}]
    best_checkpoint: Mapped[str | None] = mapped_column(String(200))
    data_manifest: Mapped[dict] = mapped_column(JSONB, default=dict, server_default="{}")
    log: Mapped[list] = mapped_column(JSONB, default=list, server_default="[]")
    work_dir: Mapped[str | None] = mapped_column(String(1000))
    output_model_version_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("model_versions.id", ondelete="SET NULL"))
    evaluation_run_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("evaluation_runs.id", ondelete="SET NULL"))
    error: Mapped[dict | None] = mapped_column(JSONB)
    worker: Mapped[str | None] = mapped_column(String(200))
    pid: Mapped[int | None] = mapped_column(Integer)
    submitted_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    submitted_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, server_default=func.now())
    started_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    heartbeat_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    duration_s: Mapped[float | None] = mapped_column(Float)


class ModelPublication(UUIDPk, Base):
    """Preparation of a Zenodo publication for an institutional model version.

    The package (weights, model card, Zenodo metadata) is generated by the platform; it is
    published only by a person, after every listed author has been confirmed by the project PI.
    """
    __tablename__ = "model_publications"

    model_version_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("model_versions.id", ondelete="CASCADE"), index=True)
    title: Mapped[str] = mapped_column(String(300))
    description: Mapped[str] = mapped_column(Text)
    authors: Mapped[list] = mapped_column(JSONB)  # [{name, affiliation, orcid}]
    license_id: Mapped[str] = mapped_column(String(100))
    keywords: Mapped[list] = mapped_column(JSONB, default=list, server_default="[]")
    approved_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    approved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    approval_statement: Mapped[str | None] = mapped_column(Text)
    package_key: Mapped[str | None] = mapped_column(String(300))
    package_sha256: Mapped[str | None] = mapped_column(String(64))
    package_bytes: Mapped[int | None] = mapped_column(BigInteger)
    published_doi: Mapped[str | None] = mapped_column(String(120))  # recorded after a person publishes it
    created_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, server_default=func.now())
    is_withdrawn: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false")
